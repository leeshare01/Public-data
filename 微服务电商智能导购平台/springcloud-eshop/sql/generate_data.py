# 默认属性（当分类没有特定模板时使用）
DEFAULT_ATTRIBUTES = [("材质", "高品质"), ("产地", "中国"), ("品牌", "自有品牌"), ("风格", "简约"), ("适用场景", "日常")]


def generate_products():
    """生成所有 INSERT SQL"""
    lines = []
    lines.append("-- ============================================================")
    lines.append("-- 商品测试数据导入脚本")
    lines.append(f"-- 生成时间: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"-- 商品数: {len(PRODUCT_TEMPLATES)}")
    lines.append("-- ============================================================")
    lines.append("")
    lines.append("USE eshop_product;")
    lines.append("")

    # ====== 商品 INSERT ======
    lines.append("-- ====== 商品表 ======")
    lines.append(f"INSERT INTO `product` (`id`, `name`, `subtitle`, `brand`, `description`, `main_image`, `sub_images`, `category_id`, `price`, `original_price`, `sales`, `status`, `keywords`, `create_time`, `update_time`) VALUES")
    product_ids = []
    prod_id = 1
    for idx, (name, subtitle, brand, desc, cat_id, orig, price, sales) in enumerate(PRODUCT_TEMPLATES):
        product_ids.append(prod_id)
        safe_name = sanitize_filename(name)
        main_img = f"/images/products/{safe_name}_1.jpg"
        sub_imgs = json.dumps([
            f"/images/products/{safe_name}_2.jpg",
            f"/images/products/{safe_name}_3.jpg",
            f"/images/products/{safe_name}_4.jpg",
        ], ensure_ascii=False)
        # 关键词从名称提取
        kw = name.replace("", " ")
        create_time = datetime(2026, 1, 1) + timedelta(days=random.randint(0, 200))
        update_time = create_time + timedelta(days=random.randint(0, 30))
        status = 1
        # 缩进格式化 — 最后一行末尾不用逗号
        sep = "," if prod_id < len(PRODUCT_TEMPLATES) else ""
        def esc(s):
            return s.replace("'", "''")
        lines.append(f"({prod_id}, '{esc(name)}', '{esc(subtitle)}', '{esc(brand)}', '{esc(desc)}', '{main_img}', '{sub_imgs}', {cat_id}, {price}, {orig}, {sales}, {status}, '{esc(kw)}', '{create_time.strftime('%Y-%m-%d %H:%M:%S')}', '{update_time.strftime('%Y-%m-%d %H:%M:%S')}'){sep}")
        prod_id += 1
    lines.append(";")

    # ====== SKU INSERT ======
    lines.append("")
    lines.append("-- ====== SKU 表 ======")
    lines.append(f"INSERT INTO `product_sku` (`product_id`, `sku_code`, `spec_values`, `price`, `stock`, `locked_stock`, `image`, `sort_order`) VALUES")
    sku_lines = []
    sku_counter = 0
    pid = 1
    for idx, (name, subtitle, brand, desc, cat_id, orig, price, sales) in enumerate(PRODUCT_TEMPLATES):
        # 找匹配的 SKU 模板（按分类或取最近分类）
        sku_tmpl = SKU_TEMPLATES.get(cat_id, SKU_TEMPLATES.get(21, {"colors": [], "sizes": ["标准"], "field": ["款式", None]}))
        colors = sku_tmpl["colors"]
        sizes = sku_tmpl["sizes"]
        field_names = sku_tmpl["field"]
        safe_name = sanitize_filename(name)

        # 生成最多 6 个 SKU
        count = 0
        for ci, color in enumerate(colors[:3]):  # 最多取前3种颜色
            for si, size in enumerate(sizes[:3]):  # 最多取前3种尺码
                if count >= 6:
                    break
                count += 1
                sku_counter += 1
                sku_code = f"SKU{pid:03d}{chr(65+ci)}{si+1}"
                # spec_values 构建
                spec = {}
                if field_names[0] and color:
                    spec[field_names[0]] = color
                if field_names[1] and size:
                    spec[field_names[1]] = size
                spec_json = json.dumps(spec, ensure_ascii=False)
                # SKU价格 = 基础价 + 随机浮动
                sku_price = round(price * (0.95 + random.random() * 0.15), 2)
                if sku_price < 1:
                    sku_price = price
                stock = random.randint(20, 500)
                sku_img = f"/images/products/{safe_name}_1.jpg"
                sep = "," if (pid < len(PRODUCT_TEMPLATES) or ci < len(colors[:3]) - 1 or si < len(sizes[:3]) - 1) else ""
                sku_lines.append(f"({pid}, '{sku_code}', '{spec_json}', {sku_price}, {stock}, 0, '{sku_img}', {count})")
        pid += 1
    lines.append(",\n".join(sku_lines))
    lines.append(";")

    # ====== Attribute INSERT ======
    lines.append("")
    lines.append("-- ====== 属性表 ======")
    lines.append(f"INSERT INTO `product_attribute` (`product_id`, `attr_name`, `attr_value`, `sort_order`) VALUES")
    attr_lines = []
    pid = 1
    for name, subtitle, brand, desc, cat_id, orig, price, sales in PRODUCT_TEMPLATES:
        attrs = ATTRIBUTE_TEMPLATES.get(cat_id, DEFAULT_ATTRIBUTES)
        for order, (aname, avalue) in enumerate(attrs):
            # 部分属性稍微个性化
            if aname == "品牌" and avalue == "自有品牌":
                avalue = brand
            if aname == "面料":
                avalue = avalue if avalue else "高品质面料"
            sep = "," if (pid < len(PRODUCT_TEMPLATES) or order < len(attrs) - 1) else ""
            attr_lines.append(f"({pid}, '{aname}', '{avalue}', {order+1})")
        pid += 1
    lines.append(",\n".join(attr_lines))
    lines.append(";")

    lines.append("")
    lines.append("-- 数据导入完成！")
    lines.append(f"-- 共 {len(PRODUCT_TEMPLATES)} 个商品")
    lines.append(f"-- 共 {len(sku_lines)} 个 SKU")
    lines.append(f"-- 共 {len(attr_lines)} 个属性")

    return {
        "sql": "\n".join(lines),
        "stats": {
            "products": len(PRODUCT_TEMPLATES),
            "skus": len(sku_lines),
            "attributes": len(attr_lines),
        }
    }


